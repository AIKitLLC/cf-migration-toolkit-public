// Public Netlify origin for the D1 fixture (`--old` on a live verify). The bundle is a plain static folder:
// Netlify Drop and `netlify deploy --dir` both apply `_redirects` and `_headers` from it.
export const NETLIFY_FIXTURE_DIR = join(D1_ROOT, 'netlify-fixture', 'dist');
const PLACEHOLDER_ORIGIN = 'https://plinthwick-sample.example';
// Explicit allowlist of files copied from site/dist. Anything else in site/dist (the Cloudflare
// `_redirects`/`_headers` and conversion reports written by `cfmt convert`) is never copied.
export const COPIED_FILES = ['index.html', 'faq.html', 'form-stub.html', 'favicon.svg', 'robots.txt'] as const;
// HTML pages: Netlify form attributes are removed so Netlify Forms has nothing to detect.
const HTML_FILES = new Set<string>(['index.html', 'faq.html', 'form-stub.html']);
export const BUNDLE_FILES = [...COPIED_FILES, 'sitemap.xml', '_redirects', '_headers'].sort();

// NETLIFY_FIXTURE_ORIGIN is required. It must be https://<site>.netlify.app unless
// NETLIFY_FIXTURE_ORIGIN_OVERRIDE=1 allows another bare https origin.
export function fixtureOrigin(value: string | undefined, allowOverride = false): string {
  if (!value) throw new Error('NETLIFY_FIXTURE_ORIGIN is required, for example https://<site>.netlify.app');
  const url = new URL(value);
  if (url.protocol !== 'https:' || url.pathname !== '/' || url.search || url.hash || url.username || url.password || url.port) {
    throw new Error('NETLIFY_FIXTURE_ORIGIN must be a bare https origin');
  }
  if (!allowOverride && !/^[a-z0-9-]+\.netlify\.app$/.test(url.hostname)) {
    throw new Error('NETLIFY_FIXTURE_ORIGIN must be https://<site>.netlify.app (set NETLIFY_FIXTURE_ORIGIN_OVERRIDE=1 for another host)');
  }
  return url.origin;
}

// Removes data-netlify / netlify / netlify-honeypot / data-netlify-* attributes. Bundle output only.
export function stripNetlifyFormAttributes(html: string): string {
  return html.replace(/<form\b[^>]*>/gi, (tag) =>
    tag.replace(/\s+(?:data-netlify(?:-[a-z-]+)?|netlify(?:-honeypot)?)(?:\s*=\s*(?:"[^"]*"|'[^']*'|[^\s>]+))?(?=[\s>/])/gi, ''),
  );
}

async function regularFile(path: string): Promise<void> {
  const info = await lstat(path);
  if (info.isSymbolicLink() || !info.isFile()) throw new Error(`Refusing non-regular file or symlink: ${path}`);
}

export async function assertBundleShape(outDir: string): Promise<void> {
  const entries = (await readdir(outDir)).sort();
  if (JSON.stringify(entries) !== JSON.stringify(BUNDLE_FILES)) {
    throw new Error(`Bundle files ${entries.join(', ')} differ from the allowlist ${BUNDLE_FILES.join(', ')}`);
  }
  for (const entry of entries) {
    await regularFile(join(outDir, entry));
    if (HTML_FILES.has(entry) && /\b(?:data-)?netlify(?:-honeypot)?\s*=/i.test(await readFile(join(outDir, entry), 'utf8'))) {
      throw new Error(`Netlify form attribute left in ${entry}`);
    }
  }
}

export function renderRedirects(rules: readonly RedirectRule[]): string {
  const lines = ['# Generated by scripts/d1/build-netlify-fixture.ts from site/netlify.toml. Do not edit.'];
  for (const rule of rules) {
    if (rule.query.length || rule.conditions.length) throw new Error(`Unsupported redirect condition on ${rule.from}`);
    // Keep an omitted status omitted: Netlify defaults it to 301, same as netlify.toml.
    // https://docs.netlify.com/routing/redirects/redirect-options/#http-status-codes
    lines.push([rule.from, rule.to, rule.status === null ? '' : `${rule.status}${rule.force ? '!' : ''}`].join(' ').trimEnd());
  }
  return `${lines.join('\n')}\n`;
}

export function renderHeaders(toml: string): string {
  const project = parseNetlifyConfig(toml, 'netlify.toml');
  const lines = ['# Generated by scripts/d1/build-netlify-fixture.ts from site/netlify.toml. Do not edit.'];
  for (const rule of project.headers) {
    if (rule.conditions.length) throw new Error(`Unsupported header condition on ${rule.path}`);
    lines.push(rule.path, ...rule.headers.map((field) => `  ${field.name}: ${field.value}`));
  }
  return `${lines.join('\n')}\n`;
}

export async function buildNetlifyFixture(outDir: string, origin: string): Promise<void> {
  await prepareD1Assets();
  await rm(outDir, { recursive: true, force: true });
  await mkdir(outDir, { recursive: true });
  for (const entry of COPIED_FILES) {
    const source = join(D1_DIST, entry);
    await regularFile(source);
    if (HTML_FILES.has(entry)) {
      await writeFile(join(outDir, entry), stripNetlifyFormAttributes(await readFile(source, 'utf8')));
    } else {
      await copyFile(source, join(outDir, entry));
    }
  }
  const toml = await readFile(D1_TOML, 'utf8');
  await writeFile(join(outDir, '_redirects'), renderRedirects(parseNetlifyTomlRedirects(toml)));
  await writeFile(join(outDir, '_headers'), renderHeaders(toml));
  await regularFile(join(D1_DIST, 'sitemap.xml'));
  // Only the sitemap host follows the real site. Page canonicals stay as built, so they match the
  // workers.dev deploy byte for byte; cfmt verify compares canonicals across the two origins.
  const sitemap = await readFile(join(D1_DIST, 'sitemap.xml'), 'utf8');
  await writeFile(join(outDir, 'sitemap.xml'), sitemap.replaceAll(PLACEHOLDER_ORIGIN, origin));
  await assertRulesMatch(outDir, toml);
  await assertBundleShape(outDir);
}

async function assertRulesMatch(outDir: string, toml: string): Promise<void> {
  const key = (rule: RedirectRule): string => JSON.stringify([rule.from, rule.to, rule.status, rule.force]);
  const expected = parseNetlifyTomlRedirects(toml).map(key);
  const actual = parseRedirectsFile(await readFile(join(outDir, '_redirects'), 'utf8')).map(key);
  if (JSON.stringify(expected) !== JSON.stringify(actual)) throw new Error('_redirects does not match netlify.toml');
  const hkey = (rules: { path: string; headers: readonly { name: string; value: string }[] }[]): string =>
    JSON.stringify(rules.map((rule) => [rule.path, rule.headers.map((field) => [field.name, field.value])]));
  const headersFile = parseNetlifyHeadersFile(await readFile(join(outDir, '_headers'), 'utf8'), '_headers').headers;
  if (hkey(parseNetlifyConfig(toml, 'netlify.toml').headers) !== hkey(headersFile)) {
    throw new Error('_headers does not match netlify.toml');
  }
}

// Local check: serve site/dist (the 127.0.0.1 fixture) and the bundle with the same simulator, then run
// cfmt verify --source fixture over the same URL set as the D1 parity report.
export async function verifyNetlifyFixture(outDir: string, reportDir: string): Promise<number> {
  const before = await startNetlifyStaticOrigin({ root: D1_DIST, netlifyTomlPath: D1_TOML });
  const after = await startNetlifyStaticOrigin({ root: outDir, netlifyTomlPath: D1_TOML });
  try {
    return await runCli([
      'verify', '--old', before.origin, '--new', after.origin, '--source', 'fixture',
      '--sitemap', `${before.origin}/sitemap.xml`, '--urls', D1_OLD_URLS, '--redirects', D1_TOML,
      '--fail-on-warn', '--json', join(reportDir, 'report.json'), '--md', join(reportDir, 'report.md'),
    ]);
  } finally {
    await after.close();
    await before.close();
  }
}

if (isDirectRun(import.meta.url)) {
  const origin = fixtureOrigin(process.env.NETLIFY_FIXTURE_ORIGIN, process.env.NETLIFY_FIXTURE_ORIGIN_OVERRIDE === '1');
  buildNetlifyFixture(NETLIFY_FIXTURE_DIR, origin)
    .then(async () => {
      process.stderr.write(`wrote ${relative(process.cwd(), NETLIFY_FIXTURE_DIR)} (sitemap host ${origin})\n`);
      const reportDir = join(D1_ROOT, 'netlify-fixture', 'check');
      await mkdir(reportDir, { recursive: true });
      const code = await verifyNetlifyFixture(NETLIFY_FIXTURE_DIR, reportDir);
      if (code !== 0) throw new Error(`local bundle check exited ${code}`);
    })
    .catch((error: unknown) => {
      process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`);
      process.exitCode = 1;
    });
}
