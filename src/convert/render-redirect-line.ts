export function renderRedirectLine(source: string, destination: string, status: number): string {
  return `${source} ${destination} ${status}`;
}

export const REDIRECTS_BANNER = '# Generated by cfmt convert. Each redirect includes an explicit status code.';

export function renderRedirectsFile(lines: readonly string[]): string {
  return `${[REDIRECTS_BANNER, ...lines].join('\n')}\n`;
}
