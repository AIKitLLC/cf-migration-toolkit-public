import type { WrittenHeader } from './conversion-draft.js';

export const HEADERS_BANNER = '# Generated by cfmt convert.';

export function renderHeadersFile(rules: readonly WrittenHeader[]): string {
  const blocks = rules.map((rule) => [rule.path, ...rule.lines].join('\n'));
  return `${HEADERS_BANNER}\n\n${blocks.join('\n\n')}\n`;
}
